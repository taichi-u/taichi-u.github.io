import { mkdir, writeFile, readFile, copyFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { resolve, delimiter } from "node:path";
import {
  profile,
  projects,
  education,
  earlierResearch,
  publications,
  awards,
  activities,
  skills,
} from "../content/portfolio.mjs";

// The same public content drives the website and both typeset PDFs.
const tex = (value) =>
  String(value)
    .replace(/[–—−‑]/g, "-")
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(
      /[\\{}%&#_$~^]/g,
      (c) =>
        ({
          "\\": "\\textbackslash{}",
          "{": "\\{",
          "}": "\\}",
          "%": "\\%",
          "&": "\\&",
          "#": "\\#",
          _: "\\_",
          $: "\\$",
          "~": "\\textasciitilde{}",
          "^": "\\textasciicircum{}",
        })[c],
    );
const outputDir = resolve("artifacts/latex");
const cacheDir = resolve("artifacts/tex-cache");
await mkdir(outputDir, { recursive: true });
await mkdir(cacheDir, { recursive: true });
const env = {
  ...process.env,
  PATH: ["/Library/TeX/texbin", process.env.PATH]
    .filter(Boolean)
    .join(delimiter),
  TEXMFVAR: cacheDir,
  TEXMFCACHE: cacheDir,
  SOURCE_DATE_EPOCH: String(Date.parse(profile.updated + "T00:00:00Z") / 1000),
};

for (const lang of ["en", "ja"]) {
  const ja = lang === "ja";
  const T = (value) => (Array.isArray(value) ? value[ja ? 1 : 0] : value);
  // Dates use en dashes; an open range reads "2025.08 – present".
  const when = (date) =>
    tex(date === "School years" && ja ? "中学時代" : date)
      .replace(/\s*-\s*$/, ` -- ${ja ? "現在" : "present"}`)
      .replace(/\s+-\s+/g, " -- ")
      .replace(/(\d)-(\d)/g, "$1--$2");
  const entry = ([date, title, description], compact = false) =>
    compact
      ? `\\cvcompact{${when(date)}}{${tex(T(title))}}{${tex(T(description))}}`
      : `\\cventry{${when(date)}}{${tex(T(title))}}{}{${tex(T(description))}}`;
  const section = (title, content) =>
    `\\cvsection{${tex(title)}}\n${content}\n`;
  const [year, month] = profile.updated.split("-").map(Number);
  const updated = ja
    ? `${year}年${month}月更新`
    : `Updated ${new Date(Date.UTC(year, month - 1)).toLocaleString("en", { month: "long", timeZone: "UTC" })} ${year}`;
  // The site sets organisations in capitals; the CV uses their ordinary spelling.
  const orgName = (org) =>
    org
      .split(/( · | \/ )/)
      .map((part) =>
        /^[A-Z&. ]+$/.test(part) && part.replace(/[^A-Z]/g, "").length > 5
          ? part.toLowerCase().replace(/\b[a-z]/g, (c) => c.toUpperCase())
          : part,
      )
      .join("");
  const page1 = [
    section(
      ja ? "学歴" : "Education",
      education.map((row) => entry(row)).join("\n"),
    ),
    section(
      ja ? "研究・開発" : "Research & Development",
      projects
        .map(
          (p) =>
            `\\cventry{${when(p.date)}}{${tex(T(p.title))}}{\\cvorg{${tex(orgName(p.org))}}\\enspace·\\enspace ${tex(T(p.role))}}{${tex(T(p.summary))}}`,
        )
        .join("\n"),
    ),
  ].join("\n");
  const page2 = [
    section(
      ja ? "その他の研究" : "Earlier Research",
      earlierResearch.map((row) => entry(row)).join("\n"),
    ),
    section(
      ja ? "発表・執筆" : "Presentations & Papers",
      [...publications]
        .sort((a, b) => b[0].localeCompare(a[0]))
        .map(
          ([date, type, title, venue, url]) =>
            `\\cventry{${when(date)}}{${url ? `\\href{${tex(url)}}{${tex(T(title))}}` : tex(T(title))}}{${tex(venue)}\\enspace·\\enspace ${tex(T(type))}}{}`,
        )
        .join("\n"),
    ),
    section(
      ja ? "受賞・採択" : "Awards & Scholarships",
      awards.map((row) => entry(row, true)).join("\n"),
    ),
  ].join("\n");
  const page3 = [
    section(
      ja ? "活動歴" : "Activities",
      activities.map((row) => entry(row)).join("\n"),
    ),
    section(
      ja ? "スキル・資格" : "Skills & Qualifications",
      skills
        .map(
          ([title, desc]) => `\\cvskill{${tex(T(title))}}{${tex(T(desc))}}`,
        )
        .join("\n"),
    ),
  ].join("\n");
  const source =
    `% Generated by scripts/build-cv.mjs from public portfolio content.\n` +
    `\\documentclass[a4paper,10pt]{${ja ? "ltjsarticle" : "article"}}\n` +
    (ja ? "\\usepackage[haranoaji]{luatexja-preset}\n" : "") +
    `\\input{cv/preamble.tex}\n\\hypersetup{pdftitle={${tex(T(profile.name))} - Curriculum Vitae}}\n` +
    `\\begin{document}\n` +
    (ja ? "\\renewcommand{\\cvheadstyle}[1]{#1}\\linespread{0.93}\\selectfont\n" : "") +
    `\\renewcommand{\\cvupdated}{${updated}}\n` +
    `\\cvheader{${tex(T(profile.name))}}{${ja ? "Taichi Uchida" : ""}}{\\href{mailto:${tex(profile.email)}}{${tex(profile.email)}}}{\\href{https://taichi-u.github.io/}{taichi-u.github.io}}\n` +
    `${tex(T(profile.intro))}\\par\n` +
    page1 +
    "\n" +
    page2 +
    "\n" +
    page3 +
    "\\end{document}\n";
  const stem = `taichi-uchida-${lang}`;
  await writeFile(`cv/${stem}.tex`, source);
  for (let pass = 0; pass < 2; pass++) {
    const run = spawnSync(
      process.env.LUALATEX || "lualatex",
      [
        "-interaction=nonstopmode",
        "-halt-on-error",
        "-file-line-error",
        "-no-shell-escape",
        `-output-directory=${outputDir}`,
        `cv/${stem}.tex`,
      ],
      { env, encoding: "utf8", maxBuffer: 12 * 1024 * 1024 },
    );
    if (run.error || run.status !== 0) {
      console.error(run.error || run.stdout.slice(-9000) + run.stderr);
      process.exit(1);
    }
  }
  const log = await readFile(`${outputDir}/${stem}.log`, "utf8");
  const warnings = log
    .split("\n")
    .filter((line) => /Overfull|Missing character|LaTeX Warning/.test(line));
  if (warnings.length) console.warn(lang + ": " + warnings.join("\n"));
  const output = `cv_taichiuchida${ja ? "-ja" : ""}.pdf`;
  await copyFile(`${outputDir}/${stem}.pdf`, output);
  console.log(`Built ${output} using LuaLaTeX.`);
}
